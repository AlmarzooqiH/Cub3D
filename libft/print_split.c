#include "libft.h"

void	print_split(char **s)
{
	size_t	i;

	if (!s || s[0] == NULL || !s[0][0])
	{
		printf("s = {NULL}\n");
		return ;
	}
	i = 0;
	printf("s = {");
	while (s[i] != NULL)
	{
		ft_printf("{%s}, ", s[i]);
		i++;
	}
	printf("}\n");
}
